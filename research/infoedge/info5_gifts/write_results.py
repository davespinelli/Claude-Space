#!/usr/bin/env python3
"""INFO-5: write RESULTS.md from results.json (every number in RESULTS.md comes from there)."""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = json.loads((HERE / "results.json").read_text())
D = json.loads((HERE / "diagnostics.json").read_text())


def pct(x, d=2):
    return "n/a" if x is None else f"{x * 100:+.{d}f}%"


def tt(x):
    return "n/a" if x is None else f"{x:.2f}"


def row(label, s, cost=True):
    if not s or s.get("n", 0) == 0:
        return f"| {label} | 0 | n/a | n/a | n/a | n/a |"
    ac = f"{pct(s.get('mean_after_cost'))} (t = {tt(s.get('t_after_cost'))})" if cost else "n/a"
    return (f"| {label} | {s['n']:,} | {pct(s['mean'])} | {tt(s.get('t'))} | "
            f"{s.get('share_negative', 0) * 100:.0f}% | {ac} |")


HDR = ["| Group | Events | Mean abnormal return | t (clustered by filing month) | Share negative | "
       "After 0.2% cost (short side) |", "|---|---|---|---|---|---|"]


def main():
    p = R["primary"]
    P, h1, h2 = p["primary"], p["half1"], p["half2"]
    S, I, B, C, L = R["secondary"], R["info"], R["bounds"], R["counts"], R["stage1"]
    pre, post = R["pre_rule"], R["post_rule"]
    verdict = p["verdict"]
    both_neg = (h1["mean"] < 0) and (h2["mean"] < 0)
    o = []
    w = o.append

    w("# INFO-5. Do insider stock gifts predict falling prices? Pre-registered event study\n")
    w("*Generated by `research/infoedge/info5_gifts/write_results.py` from `results.json`. The spec and every "
      "definition are in `PREREG.md` in this folder, written before any return was computed. Events: stock gifts "
      "by officers and directors reported on Form 4 and filed 2006-01 to 2026-06, worth at least $1M or at least "
      "1% of the donor's holdings. Returns: Yahoo daily prices to 2026-09-25, measured against a size-and-industry "
      "benchmark.*\n")

    bs, sg = D["by_size"], D["subgroups"]
    w("## The short answer\n")
    w(f"**{verdict} by the pre-registered rule, but I read it as a false positive, not a usable signal.** "
      f"The primary number clears the bar: after an officer or director files a large stock gift, the stock "
      f"averaged {pct(P['mean'])} against its size-and-industry benchmark over the next 60 trading days "
      f"(t = {tt(P['t'])}; bar t <= -2.5), and it was negative in both halves ({pct(h1['mean'])} and "
      f"{pct(h2['mean'])}). But checks run afterwards (not pre-registered, labelled as such below) say most of "
      f"that number is the benchmark, not the gift:\n")
    w(f"- It comes from micro caps. Under $300M the average is {pct(bs['under_300m']['bhar']['mean'])}, but the same "
      f"stocks on random dates with no gift score {pct(bs['under_300m']['placebo']['mean'])} against the same "
      f"benchmark: the equal-weighted, survivors-only, daily-rebalanced small-cap benchmark runs ahead of almost any "
      f"single small stock. In companies of $2B and more (two thirds of events) the abnormal return is "
      f"{pct(sg['all_2b_plus']['bhar']['mean'])} (t = {tt(sg['all_2b_plus']['bhar']['t'])}).")
    w(f"- Against IWM / SPY the same events show {pct(I['etf_benchmark']['mean'])} (t = {tt(I['etf_benchmark']['t'])}).")
    w(f"- It is gone since gifts had to be reported within two business days (2023 rule): {pct(post['mean'])} "
      f"(t = {tt(post['t'])}), against {pct(pre['mean'])} (t = {tt(pre['t'])}) before.")
    w(f"- One pattern does hold up: the stocks do about {abs(D['event_minus_placebo']['mean']) * 100:.1f} points worse "
      f"in the 60 days after a gift than on their own random dates (t = {tt(D['event_minus_placebo']['t'])}; "
      f"{pct(D['event_minus_placebo_etf']['mean'])} measured against IWM/SPY, t = {tt(D['event_minus_placebo_etf']['t'])}), "
      f"in every size group. But that compares a stock with its own good years; relative to peers at the same time "
      f"there is little left, so it does not give a trade.\n")
    w(*HDR[:1]); w(HDR[1])
    w(row("Primary: all qualifying gifts, by filing date", P))
    w(row(f"First half (filed {p['half1_range'][0]} to {p['half1_range'][1]})", h1))
    w(row(f"Second half (filed {p['half2_range'][0]} to {p['half2_range'][1]})", h2))
    w(row("Gifts before the 2023 rule change (gift date < 2023-02-27)", pre))
    w(row("Gifts after the rule change (due within 2 business days)", post))
    w(row("Secondary: December gifts", S["december"]))
    w(row("Secondary: CEO/CFO gifts", S["ceo_cfo"]))
    w(row("Secondary: companies under $2B", S["under_2b"]))
    w(row("Secondary, info only: pre-filing window (gift date to filing date)", S["prefiling_window"], cost=False))
    w(row("Info only: dated by gift date, days +1 to +60", S["gift_date_1_60"], cost=False))
    w("")
    w("\"After 0.2% cost\" is the mean plus 0.2 points: the expected sign is negative, so the trade is a short (or a "
      "sale avoided) and the cost moves the result toward zero. \"Share negative\" is the share of events with a "
      "negative abnormal return. The t-statistics use standard errors clustered by filing month (246 months).\n")

    w("## Why the Yes does not survive (post-hoc checks, not pre-registered)\n")
    w("These checks were added after the primary result was seen, because the primary and the IWM/SPY version disagreed. "
      "They cannot change the verdict; they say how far to trust it. Script: `diagnostics.py`; numbers: "
      "`diagnostics.json`.\n")
    w("1. **Placebo: the same stocks on random dates.** For each event, three dates were drawn at random (fixed seed) "
      "from the stock's priced history, at least 60 trading days from any of its own gift filings, and the same "
      "abnormal return was computed. If the benchmark were fair, these would average about zero.")
    w("2. **Buy-and-hold benchmark.** The same size-and-industry peers, but the benchmark is the average of each peer's "
      "own 60-day return instead of the 60-day compound of the daily average. That removes the rebalancing bias of a "
      "daily-rebalanced equal-weighted portfolio (Barber and Lyon, 1997).")
    w("3. **IWM / SPY.** The pre-registered fallback benchmark, applied to every event.\n")
    w("| Market cap on filing date | Events | Primary (size-and-industry) | Same stocks, random dates | Event minus random dates | Buy-and-hold benchmark | Against IWM/SPY | IWM/SPY, event minus random dates |")
    w("|---|---|---|---|---|---|---|---|")
    lab = {"under_300m": "Under $300M", "300m_2b": "$300M to $2B", "2b_10b": "$2B to $10B", "over_10b": "Over $10B"}
    for k, v in bs.items():
        w(f"| {lab[k]} | {v['bhar']['n']:,} | {pct(v['bhar']['mean'])} (t {tt(v['bhar']['t'])}) | "
          f"{pct(v['placebo']['mean'])} (t {tt(v['placebo']['t'])}) | {pct(v['diff']['mean'])} (t {tt(v['diff']['t'])}) | "
          f"{pct(v['bhar_bh']['mean'])} (t {tt(v['bhar_bh']['t'])}) | {pct(v['bhar_etf']['mean'])} (t {tt(v['bhar_etf']['t'])}) | "
          f"{pct(v['diff_etf']['mean'])} (t {tt(v['diff_etf']['t'])}) |")
    w(f"| All (incl. {C['mcap_unknown']:,} with unknown size) | {P['n']:,} | {pct(P['mean'])} (t {tt(P['t'])}) | "
      f"{pct(D['placebo_mean']['mean'])} (t {tt(D['placebo_mean']['t'])}) | {pct(D['event_minus_placebo']['mean'])} "
      f"(t {tt(D['event_minus_placebo']['t'])}) | {pct(D['buyhold_benchmark']['mean'])} (t {tt(D['buyhold_benchmark']['t'])}) | "
      f"{pct(I['etf_benchmark']['mean'])} (t {tt(I['etf_benchmark']['t'])}) | {pct(D['event_minus_placebo_etf']['mean'])} "
      f"(t {tt(D['event_minus_placebo_etf']['t'])}) |")
    w("")
    w("What the table says:\n")
    w(f"- The benchmark is the problem in small stocks. On random dates, micro caps score "
      f"{pct(bs['under_300m']['placebo']['mean'])} per 60 days against their benchmark, almost exactly their gift-event "
      f"number. Survivor-only, equal-weighted, daily-rebalanced small-cap portfolios compound faster than a typical "
      f"member stock. The pre-registered benchmark therefore flags almost any micro-cap event as negative.")
    w(f"- In companies of $2B and more there is no abnormal return against peers at the same time: "
      f"{pct(sg['all_2b_plus']['bhar']['mean'])} (t = {tt(sg['all_2b_plus']['bhar']['t'])}), and "
      f"{pct(sg['all_2b_plus']['bhar_etf']['mean'])} against SPY/IWM.")
    w(f"- With the buy-and-hold version of the same benchmark, the whole sample gives {pct(D['buyhold_benchmark']['mean'])} "
      f"(t = {tt(D['buyhold_benchmark']['t'])}); second half {pct(D['buyhold_benchmark_half2']['mean'])}.")
    w(f"- The event-minus-random-dates gap (about {pct(D['event_minus_placebo']['mean'])}, t = "
      f"{tt(D['event_minus_placebo']['t'])}; both halves negative: {pct(D['event_minus_placebo_half1']['mean'])} and "
      f"{pct(D['event_minus_placebo_half2']['mean'])}) is the one consistent pattern. It holds in every size group and "
      f"against every benchmark. But the random dates are the same companies' whole history, and companies whose "
      f"insiders give away large blocks of stock are companies whose stock has done well: on random dates the large "
      f"caps beat their peers by {pct(bs['over_10b']['placebo']['mean'])} per 60 days. After a gift they simply stop "
      f"beating their peers. That fits insiders giving near a high, but it is not something you can short: against "
      f"peers or the index, the post-gift return is about zero.\n")
    w("Secondary groups under the same checks:\n")
    w("| Group | Events | Primary | Against IWM/SPY | Event minus random dates |")
    w("|---|---|---|---|---|")
    glab = {"all_2b_plus": "All, $2B and over", "december": "December gifts", "december_2b_plus": "December, $2B and over",
            "december_under_2b": "December, under $2B", "ceo_cfo": "CEO/CFO", "ceo_cfo_2b_plus": "CEO/CFO, $2B and over",
            "pre_rule": "Before 2023 rule", "post_rule": "After 2023 rule", "pre_rule_2b_plus": "Before 2023 rule, $2B and over"}
    for k, v in sg.items():
        w(f"| {glab[k]} | {v['bhar']['n']:,} | {pct(v['bhar']['mean'])} (t {tt(v['bhar']['t'])}) | "
          f"{pct(v['bhar_etf']['mean'])} (t {tt(v['bhar_etf']['t'])}) | {pct(v['diff']['mean'])} (t {tt(v['diff']['t'])}) |")
    w("")

    w("## Read this first: most of the would-be events have no price\n")
    miss = L["missing_by_year"]
    prc = L["priced_by_year"]
    w(f"Yahoo only has prices for symbols that still trade. Of {L['events_all']:,} qualifying events "
      f"(issuer x filing date), {L['events_window_incomplete_dropped']:,} lack a full 60-day window, {L['events_priced']:,} have usable prices and {L['events_missing']:,} do not "
      f"({B['missing_share'] * 100:.0f}% of the events with a complete window). Reasons:\n")
    w("| Reason | Events |")
    w("|---|---|")
    for k, v in L["missing_by_reason"].items():
        w(f"| {k.replace('_', ' ')} | {v:,} |")
    w("")
    w("| Filing year | Priced events | Missing events | Missing share |")
    w("|---|---|---|---|")
    for y in sorted(set(miss) | set(prc), key=int):
        a, b = prc.get(y, 0), miss.get(y, 0)
        w(f"| {y} | {a:,} | {b:,} | {b / (a + b) * 100:.0f}% |" if a + b else f"| {y} | 0 | 0 | n/a |")
    w("")
    w(f"The list is in `data/missing_events.csv.gz` ({L['excluded_issuers']:,} issuers, in `data/excluded_issuers.csv`). "
      "As in research/oplev, the headline is re-run with every missing event assigned a -30% abnormal return "
      "(a typical delisting for poor performance) and then +15% (a typical takeover premium):\n")
    w(f"- Missing events excluded (headline): {pct(P['mean'])}, t = {tt(P['t'])}.")
    w(f"- Every missing event at -30%: {pct(B['minus30']['mean'])}, t = {tt(B['minus30']['t'])} "
      f"({B['minus30']['n']:,} events).")
    w(f"- Every missing event at +15%: {pct(B['plus15']['mean'])}, t = {tt(B['plus15']['t'])}.")
    w("")
    w("These bounds are extreme for a 60-day window (they assume the whole delisting loss or takeover premium lands "
      "inside it) and the missing events swamp the priced ones, so the bound results mostly restate the assumption. "
      "They show that the missing events could move the answer either way; they cannot rescue or sink it on their own.\n")

    w("## The primary test\n")
    w("**Question.** When an officer or director files a Form 4 reporting a stock gift worth at least $1M or at least 1% "
      "of their holdings, does the stock lag similar companies over the next 60 trading days (about three months)?\n")
    w(f"**Answer: {verdict}.** Mean buy-and-hold abnormal return {pct(P['mean'])} (t = {tt(P['t'])}); "
      f"median {pct(P['median'])}.\n")
    w("**How much to trust it.**\n")
    w(f"- Halves: {pct(h1['mean'])} (t = {tt(h1['t'])}, {h1['n']:,} events) and {pct(h2['mean'])} "
      f"(t = {tt(h2['t'])}, {h2['n']:,} events).")
    w(f"- Winsorised at 1% / 99% (information only): {pct(I['winsorised_1_99']['mean'])}, t = {tt(I['winsorised_1_99']['t'])}.")
    w(f"- Against IWM / SPY instead of the size-and-industry benchmark: {pct(I['etf_benchmark']['mean'])}, "
      f"t = {tt(I['etf_benchmark']['t'])}. Raw stock return (no benchmark): {pct(I['raw_stock_return']['mean'])}.")
    w(f"- Only the first event per company in any 60-trading-day span (no overlapping windows): "
      f"{pct(I['non_overlapping']['mean'])}, t = {tt(I['non_overlapping']['t'])} ({I['non_overlapping']['n']:,} events).")
    w(f"- t clustered by company instead of filing month: {tt(I['cluster_by_issuer']['t'])} "
      f"({I['cluster_by_issuer']['clusters']:,} companies).")
    w(f"- Shorter windows: days +1 to +5 {pct(I['days_1_5']['mean'])} (t = {tt(I['days_1_5']['t'])}); "
      f"days +1 to +20 {pct(I['days_1_20']['mean'])} (t = {tt(I['days_1_20']['t'])}).")
    w(f"- By size of gift: worth $1M or more {pct(I['value_ge_1m']['mean'])} (t = {tt(I['value_ge_1m']['t'])}, "
      f"{I['value_ge_1m']['n']:,} events); $10M or more {pct(I['value_ge_10m']['mean'])} "
      f"(t = {tt(I['value_ge_10m']['t'])}, {I['value_ge_10m']['n']:,}); qualifying only through the 1%-of-holdings "
      f"test {pct(I['pct_ge_1_only']['mean'])} (t = {tt(I['pct_ge_1_only']['t'])}, {I['pct_ge_1_only']['n']:,}).")
    bk = R["bench_kind_counts"]
    w(f"- Benchmark actually used: size-and-industry cell on every day for {bk.get('cell', 0):,} events; IWM/SPY on some "
      f"days (cell under 10 other stocks) for {bk.get('mixed', 0):,}; IWM/SPY throughout (no market cap or SIC) for "
      f"{bk.get('etf', 0):,}.")
    w("")
    w("By filing year (information only):\n")
    w("| Year | Events | Mean | t |")
    w("|---|---|---|---|")
    for y, s in sorted(I["by_year"].items(), key=lambda kv: int(kv[0])):
        w(f"| {y} | {s['n']:,} | {pct(s['mean'])} | {tt(s.get('t'))} |")
    w("")

    w("## The 2023 rule change\n")
    pl, ql = R["pre_rule_lag"], R["post_rule_lag"]
    w("Since 2023-02-27 gifts must be reported on Form 4 within two business days. Before, gifts were Form 5 items "
      "(due 45 days after the fiscal year ends) that insiders could report early on Form 4, and often did so weeks or "
      "months after the gift. In the priced events:\n")
    w(f"- Before the change: {pre['n']:,} events; days from gift to filing: median {pl['50%']:.0f}, "
      f"75th percentile {pl['75%']:.0f}, mean {pl['mean']:.0f}.")
    w(f"- After: {post['n']:,} events; median {ql['50%']:.0f}, 75th percentile {ql['75%']:.0f}, mean {ql['mean']:.0f}.\n")
    w(*HDR[:1]); w(HDR[1])
    w(row("Before the change, days +1 to +60 after filing", pre))
    w(row("After the change, days +1 to +60 after filing", post))
    w(row("Before: pre-filing window (gift to filing)", S["prefiling_window_pre_rule"], cost=False))
    w(row("After: pre-filing window (gift to filing)", S["prefiling_window_post_rule"], cost=False))
    w("")
    w("The post-change sample is about three years long, so it is much less precise than the pre-change one.\n")

    w("## Secondary tests\n")
    w(*HDR[:1]); w(HDR[1])
    for k, lab in (("december", "December gifts"), ("not_december", "Other months"),
                   ("ceo_cfo", "CEO / CFO gifts"), ("not_ceo_cfo", "Other officers and directors"),
                   ("under_2b", "Companies under $2B"), ("over_2b", "Companies $2B and over"),
                   ("mcap_unknown", "Market cap unknown (no XBRL share count)")):
        w(row(lab, S[k]))
    w("")
    w("Each secondary split by half and by rule regime:\n")
    w(*HDR[:1]); w(HDR[1])
    for k, lab in (("december", "December"), ("ceo_cfo", "CEO/CFO"), ("under_2b", "Under $2B")):
        w(row(f"{lab}, first half", S[k + "_half1"]))
        w(row(f"{lab}, second half", S[k + "_half2"]))
        w(row(f"{lab}, before 2023 change", S[k + "_pre_rule"]))
        w(row(f"{lab}, after 2023 change", S[k + "_post_rule"]))
    w("")
    pf = S["prefiling_window"]
    w(f"**Pre-filing window (information only).** From the close on the gift date to the close on the filing date "
      f"the stock's abnormal return averaged {pct(pf['mean'])} (t = {tt(pf['t'])}, {pf['n']:,} events with at least one "
      f"trading day between gift and filing). This is not tradable: the gift is not public yet.\n")
    gd = S["gift_date_1_60"]
    w(f"**Dated by gift date (information only).** Days +1 to +60 after the gift itself: {pct(gd['mean'])} "
      f"(t = {tt(gd['t'])}, {gd['n']:,} events). Also not tradable: it uses the gift date before it is public.\n")

    w("## Data and definitions\n")
    w(f"- Source: SEC Form 3/4/5 quarterly data sets 2006q1-2026q2 ({L['gift_lines_all_forms']:,} gift lines on all forms). "
      f"Form 4 and 4/A gift lines: {L['form4_gift_lines']:,}; disposals: {L['form4_gift_disposal_lines']:,}; filed by an "
      f"officer or director: {L['officer_director_lines']:,}.")
    d = L["dropped_bad_lines"]
    w(f"- Dropped as data errors: {d['zero_or_missing_shares']:,} lines with no shares, {d['gift_after_filing']:,} with the "
      f"gift dated after the filing, {d['gift_over_2y_before_filing']:,} dated more than two years before it.")
    w(f"- Duplicates removed: {L['dedup_within_filing_removed']:,} repeated lines within a filing and "
      f"{L['dedup_across_filings_removed']:,} gifts already reported in an earlier filing (amendments, spouses or "
      f"co-trustees filing the same gift). Gifts (filing x gift date): {L['gifts']:,}.")
    q = L["qualifying_by_test"]
    w(f"- Qualifying gifts: {L['qualifying_gifts']:,} ({q['both']:,} pass both tests, {q['pct_only']:,} only the "
      f"1%-of-holdings test, {q['value_only']:,} only the $1M test). Events (issuer x filing date): {L['events_all']:,}.")
    w(f"- Priced events: {C['priced_events']:,} at {C['issuers']:,} companies over {C['filing_months']} filing months; "
      f"median gift value ${C['median_value'] / 1e3:,.0f}k, median largest gift {C['median_max_pct'] * 100:.1f}% of "
      f"the donor's holdings. December {C['december']:,}; CEO/CFO {C['ceo_cfo']:,}; under $2B {C['under_2b']:,}; "
      f"$2B and over {C['over_2b']:,}; market cap unknown {C['mcap_unknown']:,}.")
    bp = R["bad_prints"]
    w(f"- Daily price errors removed across the whole panel (research/oplev rule applied to days): "
      f"{bp['round_trips_removed']:,} one-day 10x round trips and {bp['daily_returns_above_1000pct_removed']:,} daily "
      f"returns above +1,000%.")
    w(f"- Halves split at the median filing date, {R['median_filing_date_split']}.")
    w("- Benchmark: equal-weighted daily return of the other stocks in the same Fama-French 12 industry and panel "
      "market-cap quintile (re-formed each 30 June) among currently listed NYSE / Nasdaq / CBOE issuers that appear "
      "in the Form 4 data. Survivors only (see PREREG deviation 5).")
    w("- Scripts, in order: `fetch_form345.py`, `build_gifts.py`, `map_tickers.py`, `yahoo_daily_info5.py`, "
      "`fetch_meta.py`, `event_study.py all`, `diagnostics.py`, `write_results.py`. Raw downloads are in `cache/` "
      "(gitignored); `data/events.csv.gz` has every priced event with its returns, `data/missing_events.csv.gz` every "
      "qualifying event without a usable price.\n")

    w("## For picking stocks\n")
    w("Do not short, or sell, a stock because an insider filed a large gift. The pre-registered test says Yes, but the "
      "signal lives where the benchmark is weakest (micro caps, and December filings, whose windows cover "
      "January, when small-cap benchmarks tend to run hottest), it is zero against the index and zero in companies over $2B, and it has vanished "
      "since 2023, when gifts started being reported within two days. What is real is milder: after a big gift the "
      "stock tends to stop outperforming. At most, treat a large gift as a reason not to add to a winner, not as a "
      "trade.\n")
    (HERE / "RESULTS.md").write_text("\n".join(o) + "\n")
    print("wrote RESULTS.md")


if __name__ == "__main__":
    main()
