"""
Customer alias list for INFO-1: large US-listed companies (including US-listed ADRs)
and a few unambiguous wholly owned subsidiaries, mapped to the listed parent.

Built from (1) the brief's starter list and (2) the most frequent customer names in a
random discovery sample of 1,500 concentration-disclosing 10-Ks (data/discovery_names.csv).

Each entry:
  id         customer id used in the link table
  spell      plain spellings (used for the full-text-search phrase templates and, after
             escaping, for the in-document regex; case-sensitive, hyphen/space/apostrophe
             tolerant)
  tickers    [(yahoo_ticker, first_month, last_month)]: which price series gives the
             listed parent's return in which months (None = open). A customer month with
             no listed series is not a signal (the customer was not listed / no price).
  not_after  regex: an alias match followed by this is not the customer (e.g. "Apple
             Hospitality")
  not_before regex: an alias match preceded by this is not the customer
Treated as no link (never in this list): governments and agencies, unnamed customers
("Customer A", "a distributor"), private companies, and companies listed only abroad.
"""
