# ---------------------------------------------------------------------------- regex
def _spell_re(s: str) -> str:
    """Escape a spelling; hyphens/spaces/apostrophes/periods interchangeable."""
    out = []
    for ch in s:
        if ch in "- ":
            out.append(r"[\s\-]?" if ch == "-" else r"[\s\-]+")
        elif ch == "'":
            out.append(r"['’]?\s?")
        elif ch == ".":
            out.append(r"\.?\s?")
        elif ch == "&":
            out.append(r"\s?(?:&|and)\s?")
        else:
            out.append(re.escape(ch))
    return "".join(out)


def compiled():
    """[(id, compiled regex, not_after, not_before)] longest spellings first."""
    out = []
    for c in C:
        sp = sorted(set(c["spell"]), key=len, reverse=True)
        pat = r"(?<![A-Za-z0-9&])(?:" + "|".join(_spell_re(s) for s in sp) + r")(?![A-Za-z0-9])"
        out.append((c["id"], re.compile(pat), re.compile(c["not_after"]) if c["not_after"] else None,
                    re.compile(c["not_before"]) if c["not_before"] else None))
    return out
